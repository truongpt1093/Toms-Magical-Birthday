import os
import struct
import json
import base64

# Directory for 3D (Kenney Mini Characters)
glb_dir_3d = r"D:\Cá nhân\Codex\Toms-Magical-Birthday\3D\Models\GLB format"
colormap_path_3d = os.path.join(glb_dir_3d, "Textures", "colormap.png")
with open(colormap_path_3d, "rb") as f:
    colormap_b64_3d = "data:image/png;base64," + base64.b64encode(f.read()).decode('ascii')

# Directory for 3D2 (Kenney Mini Arena)
glb_dir_3d2 = r"D:\Cá nhân\Codex\Toms-Magical-Birthday\3D2\Models\GLB format"
colormap_path_3d2 = os.path.join(glb_dir_3d2, "Textures", "colormap.png")
with open(colormap_path_3d2, "rb") as f:
    colormap_b64_3d2 = "data:image/png;base64," + base64.b64encode(f.read()).decode('ascii')

models_3d = [
    'character-male-a', 'character-male-b', 'character-male-c',
    'character-male-d', 'character-male-e', 'character-male-f',
    'character-female-a', 'character-female-b', 'character-female-c',
    'character-female-d', 'character-female-e', 'character-female-f',
    'wheelchair', 'aid-sunglasses', 'aid-glasses'
]

models_3d2 = [
    'wall-gate', 'wall', 'column', 'stairs', 'tree', 'banner', 'trophy', 'statue', 'character-soldier', 'border-straight'
]

packed_data = {}

def pack_glb(dir_path, model_name, colormap_uri):
    glb_path = os.path.join(dir_path, f"{model_name}.glb")
    with open(glb_path, "rb") as f:
        glb_bytes = f.read()

    magic, version, length = struct.unpack('<4sII', glb_bytes[:12])
    chunk_len, chunk_type = struct.unpack('<I4s', glb_bytes[12:20])
    json_bytes = glb_bytes[20:20+chunk_len]
    json_str = json_bytes.decode('utf-8')
    gltf_json = json.loads(json_str)

    # Embed texture
    for img in gltf_json.get('images', []):
        if 'uri' in img and 'colormap' in img['uri']:
            img['uri'] = colormap_uri

    new_json_bytes = json.dumps(gltf_json, separators=(',', ':')).encode('utf-8')
    pad = (4 - (len(new_json_bytes) % 4)) % 4
    new_json_bytes += b' ' * pad
    new_chunk_len = len(new_json_bytes)

    bin_chunk = glb_bytes[20+chunk_len:]
    new_total_len = 12 + 8 + new_chunk_len + len(bin_chunk)
    new_header = struct.pack('<4sII', magic, version, new_total_len)
    new_json_header = struct.pack('<I4s', new_chunk_len, chunk_type)

    new_glb = new_header + new_json_header + new_json_bytes + bin_chunk
    b64_str = base64.b64encode(new_glb).decode('ascii')
    packed_data[model_name] = b64_str
    print(f"Packed {model_name}: {len(glb_bytes)} bytes -> base64 {len(b64_str)} chars")

print("--- Packing 3D Characters ---")
for m in models_3d:
    pack_glb(glb_dir_3d, m, colormap_b64_3d)

print("\n--- Packing 3D2 Environment Models ---")
for m in models_3d2:
    pack_glb(glb_dir_3d2, m, colormap_b64_3d2)

out_js = r"D:\Cá nhân\Codex\Toms-Magical-Birthday\3D\models-data.js"
with open(out_js, "w", encoding="utf-8") as f:
    f.write("// Autogenerated self-contained 3D models for Tom's Magical Birthday\n")
    f.write("// Allows direct execution via file:// protocol without local web server\n")
    f.write("window.KENNEY_MODELS_DATA = ")
    json.dump(packed_data, f)
    f.write(";\n")

print(f"\nSuccessfully generated {out_js} ({os.path.getsize(out_js)} bytes, {len(packed_data)} models total)")
